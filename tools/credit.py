#!/usr/bin/env python3
"""Write CREDITS.md: who added each proved theorem and each certificate.

Read from git history (commit author plus Co-Authored-By trailers), so it is
not part of the referee: it cannot be reproduced before a commit exists.
Maintainers run it on main after merging. It lists results, not a ranking.
"""
import re, subprocess, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import board

def who(args):
    r = subprocess.run(["git", "log", "--reverse", "--format=%h|%an|%(trailers:key=Co-Authored-By,valueonly,separator=%x2C )"] + args,
                       cwd=ROOT, capture_output=True, text=True).stdout.splitlines()
    if not r:
        return "not yet committed"
    h, author, co = r[0].split("|", 2)
    co = re.sub(r"\s*<[^>]*>", "", co).strip()
    return f"{author}{' with ' + co if co else ''} ({h})"

lines = ["# Credits", "", "Generated by `tools/credit.py` from git history. A list of results, not a ranking.", "", "## Theorems", ""]
for d in board.declarations():
    if not d["open"]:
        lines.append(f"- `{d['name']}`: {who(['-S', 'theorem ' + d['name'], '--', 'DetComplexity', ':(exclude)DetComplexity/Open'])}")
lines += ["", "## Certificates", ""]
for f in sorted((ROOT / "data" / "certificates").glob("*.json")):
    lines.append(f"- `{f.name}`: {who(['--diff-filter=A', '--', str(f.relative_to(ROOT))])}")
(ROOT / "CREDITS.md").write_text("\n".join(lines) + "\n")
print(f"CREDITS: {len(lines) - 9} entries")
